import test from "node:test";
import assert from "node:assert/strict";
const data = new Map<string,string>();
Object.defineProperty(globalThis,"localStorage",{ value: { getItem: (key:string) => data.get(key) || null, setItem: (key:string,value:string) => data.set(key,value), removeItem: (key:string) => data.delete(key) } });

test("browser store persists workflow edits, approvals, revisions and appointments", async () => {
  const { useAppStore, ensureSeeded } = await import("@/lib/store");
  useAppStore.getState().setHasHydrated(true); ensureSeeded();
  const patient = useAppStore.getState().patients[0];
  const visit = patient.visits[0];
  const summary = useAppStore.getState().generateSummary(patient.id,visit.id);
  const edited = { ...summary, sections: summary.sections.map(s => s.id === "notes" ? { ...s,text: "Clinician edit used to test persistence" } : s) };
  useAppStore.getState().saveSummary(edited,"Test clinician");
  assert.equal(useAppStore.getState().generateSummary(patient.id,visit.id).sections.find(s => s.id === "notes")?.text,edited.sections.find(s => s.id === "notes")?.text);
  const saved = useAppStore.getState().summaries[0];
  useAppStore.getState().saveSummary({ ...saved,status: "approved" },"Test clinician");
  const approved = useAppStore.getState().summaries[0];
  assert.ok(approved.approvedAt); assert.equal(approved.approvedBy,"Test clinician");
  assert.throws(() => useAppStore.getState().saveSummary(approved,"Test clinician"));
  const revision = useAppStore.getState().reviseSummary(approved.id,"Test clinician");
  assert.equal(revision.status,"draft"); assert.notEqual(revision.id,approved.id);
  assert.equal(useAppStore.getState().summaries.find(s => s.id === approved.id)?.status,"approved");
  const at = new Date().toISOString();
  const appointment = { id: crypto.randomUUID(),patientId: patient.id,startsAt: at,reason: "Synthetic workflow test",status: "scheduled" as const,createdAt: at,updatedAt: at };
  useAppStore.getState().saveAppointment(appointment);
  useAppStore.getState().saveAppointment({ ...appointment,status: "completed" });
  assert.ok(useAppStore.getState().tasks.some(t => t.sourceId === `appointment:${appointment.id}`));
  const stored = JSON.parse(data.get("diabetes-care-assistant-store")!).state;
  assert.equal(stored.patients.length,useAppStore.getState().patients.length);
  assert.equal(stored.summaries.length,2);
  await useAppStore.persist.rehydrate();
  assert.equal(useAppStore.getState().summaries[0].approvedAt,approved.approvedAt);
  const count = useAppStore.getState().patients.length;
  useAppStore.getState().resetToSeedCohort(); assert.equal(useAppStore.getState().patients.length,count);
  const restoredVisit = { ...patient.visits[0],id: crypto.randomUUID(),clinicianNote: "Restored documentation" };
  useAppStore.getState().mergeBackup({ patients: [{ ...patient,visits: [...patient.visits,restoredVisit] }],appointments: [],summaries: [],tasks: [] });
  assert.ok(useAppStore.getState().patients.find(p => p.id === patient.id)!.visits.some(v => v.id === restoredVisit.id));
  assert.equal(useAppStore.getState().summaries[0].approvedAt,approved.approvedAt);
});
